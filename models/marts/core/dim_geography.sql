-- ============================================================
-- 模型：dim_geography（地理维度表 · 含去重处理）
-- 层级：DWD 明细层 marts/core
-- 物化：table
-- 粒度：一行 = 一个邮编前缀
-- ------------------------------------------------------------
-- 【★ 本模型处理一个真实的数据质量问题：邮编重复】
--
--   源表 stg_geolocation 有 1,000,163 行，
--   但唯一邮编只有约 19,000 个：
--     同一个邮编重复几十到几百次，
--     每次经纬度略有差异（同一区域的不同测量点）。
--
--   如果不处理：
--     - 维度表主键不唯一 → JOIN 时数据会翻倍
--     - 这是维度建模的严重事故（术语叫"fan-out 扇出"）
--
-- 【处理方式：按邮编聚合，取平均经纬度】
--   为什么取平均而不是取第一条？
--     取第一条：简单，但随机性大，结果不可复现
--     取平均  ：代表该区域的"质心"，语义明确、结果稳定
--
--   ⚠️ 这个决策要写进数据字典，让所有人知道口径。
--
-- 【新手知识点：GROUP BY 和窗口函数的区别（复习）】
--   这里用 GROUP BY：
--     输入 1,000,163 行 → 输出约 19,000 行（行数变少）
--     每行得到一组统计值（AVG 经纬度、COUNT 测量点数）
--
--   这正是 GROUP BY 的典型用途：压缩 + 汇总。
--   对比 dws_customer_rfm 里的 NTILE（行数不变，只是加一列）。
--
-- 【保留 measurement_count 的价值】
--   记录每个邮编下有多少个原始测量点，
--   这本身就是有用的信息：
--     测量点多 → 该区域数据密度高（可能是城市中心）
--     测量点少 → 偏远地区
--   而且保留了溯源能力——将来质疑"为什么取平均"时，
--   能立刻算出原始数据量。
-- ============================================================

SELECT
    -- ---- 主键：邮编前缀 ----
    zip_code_prefix,

    -- ---- 聚合后的坐标（区域质心）----
    ROUND(AVG(latitude), 6)                     AS latitude_avg,      -- 平均纬度
    ROUND(AVG(longitude), 6)                    AS longitude_avg,     -- 平均经度

    -- ---- 城市/州：同一邮编下取出现最多的那个 ----
    -- 理论上同一邮编的 city/state 应该相同，
    -- 但真实数据可能有出入，用 MODE() 取众数最稳妥
    MODE(geo_city)                              AS geo_city,
    MODE(geo_state)                             AS geo_state,

    -- ---- 数据质量指标：原始测量点数 ----
    COUNT(*)                                    AS measurement_count,

    -- ---- 坐标离散度：反映该区域测量点的一致性 ----
    -- 标准差大 = 该邮编覆盖范围大（或数据质量差）
    ROUND(STDDEV(latitude), 6)                  AS latitude_stddev

FROM {{ ref('stg_geolocation') }}
GROUP BY zip_code_prefix
