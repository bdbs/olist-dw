-- ============================================================
-- 自定义质量测试：GMV 口径一致性校验
-- ------------------------------------------------------------
-- 【这个测试检查什么？】
--   标准口径 GMV（仅已送达）必须 <= 全口径 GMV（含全部状态）
--   且两者差额应等于取消金额 + 其他非送达状态金额
--
-- 【为什么需要自定义测试？】
--   dbt 内置的 unique / not_null 只能检查单字段，
--   而"两个指标之间的逻辑关系"属于【业务规则】，
--   必须自己写 SQL 断言。这是数据质量的高阶玩法。
--
-- 【测试原理】
--   dbt 的 test 约定：返回行数 = 0 才算通过。
--   所以我们要查出"不合格的行"，期望一行都查不出来。
-- ============================================================

SELECT
    order_month,
    gmv_all,
    gmv_delivered,
    gmv_cancelled,
    gmv_all - gmv_delivered AS diff
FROM {{ ref('ads_gmv_monthly') }}
-- 断言：标准口径 GMV 不可能大于全口径 GMV
-- 如果这条查出了数据，说明口径逻辑写反了
WHERE gmv_delivered > gmv_all
